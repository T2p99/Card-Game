#!/usr/bin/env python3
"""Generate the runtime and human-readable indexes for the ability ledger."""

from __future__ import annotations

import csv
import json
from collections import Counter, defaultdict
from pathlib import Path


ROOT = Path(__file__).resolve().parents[2]
LEDGER = ROOT / "Assets/Resources/CardGame/Data/Tcg/ability_registry.csv"
CS_OUTPUT = ROOT / "Assets/CardGame/Core/AbilityRegistry.Handlers.Generated.cs"
DOC_OUTPUT = ROOT / "docs/ABILITY_CATALOG.md"


def csharp_string(value: str) -> str:
    return json.dumps(value, ensure_ascii=True)


def markdown_cell(value: str) -> str:
    return value.replace("|", "\\|").replace("\n", " ")


def main() -> int:
    with LEDGER.open(encoding="utf-8", newline="") as source:
        rows = list(csv.DictReader(source))

    if not rows:
        raise SystemExit("Ability ledger is empty; generate it first.")
    if any(row["implementation_status"] != "Complete" or not row["handler"] for row in rows):
        raise SystemExit("Ability ledger still contains unmapped rules.")
    ability_ids = [row["ability_id"] for row in rows]
    if len(ability_ids) != len(set(ability_ids)):
        raise SystemExit("Ability ledger contains duplicate stable IDs.")

    by_handler: dict[str, list[dict[str, str]]] = defaultdict(list)
    for row in rows:
        by_handler[row["handler"]].append(row)

    cs_lines = [
        "// <auto-generated />",
        "using System.Collections.Generic;",
        "",
        "namespace CardGame.Core",
        "{",
        "    public static partial class AbilityRegistry",
        "    {",
        "        private static List<AbilityHandlerMetadata> CreateHandlerStock() =>",
        "            new List<AbilityHandlerMetadata>",
        "            {",
    ]
    for handler in sorted(by_handler, key=str.casefold):
        variants = by_handler[handler]
        category = variants[0]["category"]
        example = variants[0]["rule_text"]
        description = example if len(variants) == 1 else (
            f"{len(variants)} printed rules variants. Example: {example}")
        cs_lines.append(
            f"                H({csharp_string(handler)}, {csharp_string(category)}, "
            f"{csharp_string(description)}),")
    cs_lines.extend(["            };", "    }", "}", ""])
    CS_OUTPUT.write_text("\n".join(cs_lines), encoding="utf-8")

    category_counts = Counter(row["category"] for row in rows)
    doc_lines = [
        "# Implemented ability catalog",
        "",
        "This is the generated index of executable ability handlers for the original English TCG pool.",
        f"The canonical CSV ledger contains **{len(rows)} distinct printed rules lines**, all marked `Complete`,",
        f"backed by **{len(by_handler)} runtime handlers** across **916 card printings**.",
        "",
        "The exact rule text, stable ability ID, printing count, implementation status, and example cards are in",
        "[`Assets/Resources/CardGame/Data/Tcg/ability_registry.csv`](../Assets/Resources/CardGame/Data/Tcg/ability_registry.csv).",
        "Do not edit either generated index by hand; regenerate them with:",
        "",
        "```bash",
        "python tools/rules/generate_rule_inventory.py --require-complete",
        "python tools/rules/generate_ability_stock.py",
        "python tools/rules/generate_tcg_catalog.py",
        "```",
        "",
        "## Coverage by category",
        "",
        "| Category | Printed rule lines |",
        "|---|---:|",
    ]
    for category, count in sorted(category_counts.items(), key=lambda item: item[0].casefold()):
        doc_lines.append(f"| {markdown_cell(category)} | {count} |")
    doc_lines.extend([
        "",
        "## Runtime handler stock",
        "",
        "| Handler | Category | Rule variants | Example printed rule |",
        "|---|---|---:|---|",
    ])
    for handler in sorted(by_handler, key=str.casefold):
        variants = by_handler[handler]
        doc_lines.append(
            f"| `{markdown_cell(handler)}` | {markdown_cell(variants[0]['category'])} | "
            f"{len(variants)} | {markdown_cell(variants[0]['rule_text'])} |")
    doc_lines.append("")
    DOC_OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    DOC_OUTPUT.write_text("\n".join(doc_lines), encoding="utf-8")

    print(f"Generated {len(by_handler)} handler records from {len(rows)} rules lines.")
    print(CS_OUTPUT.relative_to(ROOT))
    print(DOC_OUTPUT.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
