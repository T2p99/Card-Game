#!/usr/bin/env python3
"""Generate the pure-C# runtime catalog for all original English TCG printings."""

from __future__ import annotations

import csv
import json
from pathlib import Path

from generate_rule_inventory import MANIFEST_DIR, OUTPUT, ROOT, clean_line, generate, stable_id


DESTINATION = ROOT / "Assets/CardGame/Core/TcgCatalog.Generated.cs"
CIVILIZATIONS = {"Light", "Water", "Darkness", "Fire", "Nature"}


def cs_string(value: str) -> str:
    return json.dumps(value, ensure_ascii=True)


def cs_array(values: list[str], expression) -> str:
    if not values:
        return "Array.Empty<" + ("Civilization" if expression("X").startswith("Civilization.") else "string") + ">()"
    return "new[] { " + ", ".join(expression(value) for value in values) + " }"


def load_cards() -> list[dict[str, str]]:
    cards: list[dict[str, str]] = []
    for path in sorted(MANIFEST_DIR.glob("*.csv")):
        if path == OUTPUT:
            continue
        with path.open(encoding="utf-8-sig", newline="") as source:
            cards.extend(csv.DictReader(source))
    return cards


def generate_catalog() -> None:
    generate()
    with OUTPUT.open(encoding="utf-8", newline="") as source:
        handlers = {row["rule_text"].casefold(): row["handler"] for row in csv.DictReader(source)}
    lines: list[str] = [
        "// <auto-generated />",
        "using System;",
        "using System.Collections.Generic;",
        "",
        "namespace CardGame.Core",
        "{",
        "    public static partial class TcgCatalog",
        "    {",
        "        private static List<CardDefinition> CreatePrintings()",
        "        {",
        "            return new List<CardDefinition>",
        "            {",
    ]
    for card in load_cards():
        civilizations = [card["civilization"]]
        # The source site exports a secondary civilization in the rarity field
        # for multicolored cards. Preserve it as game data.
        if card["rarity"] in CIVILIZATIONS:
            civilizations.append(card["rarity"])
        races = [race.strip() for race in card["race"].split("/") if race.strip()]
        card_type = {
            "Creature": "CardType.Creature",
            "Spell": "CardType.Spell",
            "Evolution Creature": "CardType.EvolutionCreature",
        }[card["card_type"]]
        rule_lines = [clean_line(line) for line in card["card_text"].replace("\r", "").splitlines() if clean_line(line)]
        printed_rules = (
            "Array.Empty<PrintedRuleLine>()" if not rule_lines else
            "new[] { " + ", ".join(
                f"new PrintedRuleLine({cs_string(stable_id(line))}, {cs_string(line)}, {cs_string(handlers[line.casefold()])})" for line in rule_lines
            ) + " }"
        )
        lines.append(
            "                C(" + ", ".join([
                cs_string(card["card_id"]),
                cs_string(card["card_name"]),
                "new[] { " + ", ".join(f"Civilization.{civ}" for civ in civilizations) + " }",
                str(int(card["cost"] or 0)),
                card_type,
                "Array.Empty<string>()" if not races else "new[] { " + ", ".join(cs_string(race) for race in races) + " }",
                str(int(card["power"] or 0)),
                cs_string(card["card_set"]),
                cs_string(card["collector_number"]),
                str(int(card["media_id"])),
                cs_string(card["card_text"]),
                printed_rules,
            ]) + "),"
        )
    lines += [
        "            };",
        "        }",
        "    }",
        "}",
        "",
    ]
    DESTINATION.write_text("\n".join(lines), encoding="utf-8")
    print(f"Generated {len(load_cards())} printings in {DESTINATION.relative_to(ROOT)}")


if __name__ == "__main__":
    generate_catalog()
